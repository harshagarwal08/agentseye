// "Your own relay": deploys AgentsEye's relay to the user's own (free) Cloudflare account with wrangler, then points
// this Mac at it. Nobody shares a relay with strangers, nobody depends on anyone else's Cloudflare quota, and the
// relay that serves your phone's app code is one you control.
//
//   agentseye relay deploy        interactive: signs in to Cloudflare in the browser if needed
//   CLOUDFLARE_API_TOKEN=… agentseye relay deploy   for networks where the browser sign-in fails (proxies)
//
// The relay also serves the phone app, so after AgentsEye updates the relay is redeployed (boot()) to ship the new
// phone UI. That runs without a terminal and succeeds when wrangler's saved sign-in or an API token is available.
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { DATA, readJson, writeJson } from './paths.js';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(DATA, 'own-relay.json');
const BUILD = path.join(DATA, 'relay-build');
const LOG = path.join(DATA, 'relay-deploy.log');
const appVersion = () => readJson(path.join(APP, 'package.json'), {}).version || '';
const repo = () => readJson(path.join(DATA, 'install.json'), {}).repo || 'harshagarwal08/agentseye';

export const saved = () => readJson(FILE, null);
export function status() {
  const s = saved();
  return s ? { configured:true, url:s.url, name:s.name, version:s.version, deployedAt:s.deployedAt, outdated:s.version !== appVersion(), lastError:s.lastError || '' } : { configured:false };
}

// Worker names: lowercase letters, digits and dashes, up to 63 characters.
export const workerName = macId => `agentseye-${String(macId || '').toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 10) || 'relay'}`;

export function wranglerToml({ name, repo: source }) {
  return `# Generated by \`agentseye relay deploy\`. Your personal AgentsEye relay.
name = "${name}"
main = "worker.js"
compatibility_date = "2026-10-01"
workers_dev = true

[assets]
directory = "../public"
binding = "ASSETS"
run_worker_first = true
html_handling = "none"
not_found_handling = "none"

[[durable_objects.bindings]]
name = "MACS"
class_name = "MacRoom"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["MacRoom"]

[vars]
REPO = "${source}"
`;
}

// A clean copy of just what the Worker needs: relay sources, the phone app, and package.json (for its version).
export function prepare(name) {
  fs.rmSync(BUILD, { recursive:true, force:true });
  fs.mkdirSync(path.join(BUILD, 'relay'), { recursive:true });
  for (const f of ['worker.js', 'core.js', 'mac-room.js', 'install.js']) fs.copyFileSync(path.join(APP, 'relay', f), path.join(BUILD, 'relay', f));
  fs.cpSync(path.join(APP, 'public'), path.join(BUILD, 'public'), { recursive:true });
  fs.copyFileSync(path.join(APP, 'package.json'), path.join(BUILD, 'package.json'));
  fs.writeFileSync(path.join(BUILD, 'relay', 'wrangler.toml'), wranglerToml({ name, repo:repo() }));
  return path.join(BUILD, 'relay');
}

// The workers.dev address wrangler prints after a deploy.
export function deployedUrl(output, name) {
  const urls = String(output).match(/https:\/\/[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev/gi) || [];
  return urls.find(u => u.toLowerCase().includes(`//${name}.`)) || urls[0] || '';
}

const npx = () => {
  const local = path.join(path.dirname(process.execPath), 'npx');
  return fs.existsSync(local) ? local : 'npx';
};
const env = () => ({ ...process.env, PATH:`${path.dirname(process.execPath)}:${process.env.PATH || '/usr/bin:/bin'}`, WRANGLER_SEND_METRICS:'false' });

// Interactive runs go through `script` so wrangler still sees a terminal (it only offers browser sign-in and the
// workers.dev setup prompt in one) while its output is recorded for us to read the address from.
function wrangler(args, { cwd, interactive }) {
  return new Promise(resolve => {
    const cmd = [npx(), '--yes', 'wrangler@4', ...args];
    if (interactive && process.stdin.isTTY) {
      fs.rmSync(LOG, { force:true });
      const child = spawn('/usr/bin/script', ['-q', LOG, ...cmd], { cwd, env:env(), stdio:'inherit' });
      child.on('close', code => resolve({ ok:code === 0, out:fs.existsSync(LOG) ? fs.readFileSync(LOG, 'utf8') : '' }));
      child.on('error', e => resolve({ ok:false, out:e.message }));
      return;
    }
    const child = spawn(cmd[0], cmd.slice(1), { cwd, env:{ ...env(), CI:'1' }, stdio:['ignore', 'pipe', 'pipe'] });
    let out = '';
    child.stdout.on('data', c => { out += c; });
    child.stderr.on('data', c => { out += c; });
    child.on('close', code => resolve({ ok:code === 0, out }));
    child.on('error', e => resolve({ ok:false, out:e.message }));
  });
}

async function reachable(url, tries = 12) {
  for (let i = 0; i < tries; i++) {
    try { if ((await fetch(`${url}/health`, { signal:AbortSignal.timeout(5000) })).ok) return true; } catch {}
    await new Promise(r => setTimeout(r, 5000));
  }
  return false;
}

export async function deploy({ interactive = true, log = console.log } = {}) {
  const relay = await import('./relay-client.js');
  const { macId } = relay.settings();
  const name = saved()?.name || workerName(macId);
  const cwd = prepare(name);
  if (interactive && !process.env.CLOUDFLARE_API_TOKEN) {
    const who = await wrangler(['whoami'], { cwd, interactive:false });
    if (!/You are logged in|associated with the email/i.test(who.out)) {
      log('● Sign in to Cloudflare in the browser window that opens (a free account is enough)…');
      const login = await wrangler(['login'], { cwd, interactive:true });
      if (!login.ok) throw new Error('Cloudflare sign-in did not finish. Behind a company proxy? Create an API token (Cloudflare dashboard → My Profile → API Tokens → "Edit Cloudflare Workers" template) and run:\n  CLOUDFLARE_API_TOKEN=<token> agentseye relay deploy');
    }
  }
  log(`● Deploying your relay "${name}" to Cloudflare…`);
  const r = await wrangler(['deploy'], { cwd, interactive });
  const url = deployedUrl(r.out, name);
  if (!r.ok || !url) {
    const s = saved();
    if (s) writeJson(FILE, { ...s, lastError:r.out.slice(-600) });
    throw new Error(`Deploy failed.${r.out ? `\n${r.out.trim().split('\n').slice(-8).join('\n')}` : ''}`);
  }
  writeJson(FILE, { name, url, version:appVersion(), deployedAt:Date.now() });
  log(`● Deployed: ${url}`);
  log('● Waiting for the address to come online (new workers.dev addresses can take a minute)…');
  if (!await reachable(url)) log('  Not answering yet. AgentsEye keeps retrying in the background.');
  return { name, url };
}

// After AgentsEye updates, redeploy so the phone gets the matching app. At most once per version and day.
export function boot() {
  const s = saved();
  if (!s || s.version === appVersion() || (s.triedVersion === appVersion() && Date.now() - (s.triedAt || 0) < 86400000)) return;
  writeJson(FILE, { ...s, triedVersion:appVersion(), triedAt:Date.now() });
  setTimeout(() => deploy({ interactive:false, log:m => console.log(`${new Date().toISOString()} own relay: ${m}`) })
    .catch(e => console.log(`${new Date().toISOString()} own relay: redeploy failed. Run "agentseye relay deploy" in Terminal. ${String(e.message).split('\n')[0]}`)), 30000).unref();
}
